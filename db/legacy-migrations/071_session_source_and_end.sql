-- 071 — Where a session came from, how it ended, and Talk now searches (2026-10-16)
--
-- Analytics only: nothing reads these to move money or decide availability.
-- The app writes them in separate best-effort updates, so it works the same
-- before and after this migration is run.

-- 'talk' (Talk now, /talk) or 'browse' (a listener's profile / waiting-screen switch).
-- NULL = booked before this migration.
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS booked_via text;

-- Groups the requests of ONE Talk now search (each request = one "hop").
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS talk_search_id uuid;

-- How a session that went live ended:
--   'seeker' / 'listener' — that person pressed End (or left the session)
--   'time_up'             — the booked time ran out
--   'dropped'             — nobody ended it; closed by the cleanup/expiry job
--                           (app closed, network lost, battery died)
-- NULL = ended before this migration (or never went live — see cancel_reason).
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS ended_by text;

CREATE INDEX IF NOT EXISTS sessions_talk_search_idx ON sessions (talk_search_id) WHERE talk_search_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS sessions_booked_via_created_idx ON sessions (booked_via, created_at) WHERE booked_via IS NOT NULL;

-- One row per Talk now search a signed-in seeker started (also the ones where
-- nobody was online, or the seeker stopped at the price screen).
CREATE TABLE IF NOT EXISTS talk_searches (
  id          uuid PRIMARY KEY,                -- generated by the /talk page
  seeker_id   uuid NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  free        boolean,                         -- free 5-minute trial search
  candidates  integer                          -- listeners available when it started
);
CREATE INDEX IF NOT EXISTS talk_searches_created_idx ON talk_searches (created_at);

-- Server (service role) only: no policies, so end-user tokens can't read or write.
ALTER TABLE talk_searches ENABLE ROW LEVEL SECURITY;
